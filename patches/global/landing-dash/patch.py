"""Dash no primeiro frame de aterrissagem — SPEC-056."""
from asm68k import Branch, Ins, JmpAbs, Label, LeaPc
from patchlib import Block, Hook, Patch

# Bytes livres após $3AA (orçamento do Zanretsuken). Só direcionais.
READY, TIMER, STARTING, SCANNED = 0x3AB, 0x3AC, 0x3AD, 0x3AE
WINDOW = 6


def jump_or_air_normal(track="track", original="original"):
    return [
        Ins("0c2e00040040", "cmpi.b #$4, $40(a6)"),
        Branch("beq", track),
        Ins("0c2e00080040", "cmpi.b #$8, $40(a6)"),
        Branch("beq", track),
        Ins("0c2e00030040", "cmpi.b #$3, $40(a6)"),
        Branch("bne", original),
        Ins("0c6e002a0230", "cmpi.w #$2a, $230(a6)"),
        Branch("beq", track),
        Ins("0c6e002b0230", "cmpi.w #$2b, $230(a6)"),
        Branch("beq", track),
        Ins("0c6e003a0230", "cmpi.w #$3a, $230(a6)"),
        Branch("beq", track),
        Ins("0c6e003b0230", "cmpi.w #$3b, $230(a6)"),
        Branch("bne", original),
    ]


air_taps = [
    Ins("08ae00020a68", "bclr.b #$2, $a68(a6)"),
    Ins("42ae0020", "clr.l $20(a6)"),
    *jump_or_air_normal(),
    Label("track"),
    Ins("1d7c000103ae", "move.b #$1, $3ae(a6)"),
    Ins("4eb90001ccda", "jsr $1ccda.l"),
    Branch("beq", "original"),
    Ins("1d6e021303ab", "move.b $213(a6), $3ab(a6)"),
    Ins("1d7c000603ac", "move.b #$6, $3ac(a6)"),
    Label("original"),
    JmpAbs(0x1C6D4),
]

# Depois do handler do estado: não executa dash dentro de uma subrotina
# de física, onde o resto da lógica do pulo/ataque poderia sobrescrevê-lo.
land = [
    Ins("48e7f8c0", "movem.l d0-d4/a0-a1, -(a7)"),
    # Depois do contato, o estado 4/8 pode continuar sem chamar a física
    # ou o detector do neutro. Continua lendo os toques nessa transição.
    Ins("4a2e03ae", "tst.b $3ae(a6)"),
    Branch("bne", "scan_done"),
    Ins("082e00040060", "btst.b #$4, $60(a6)"),
    Branch("bne", "scan_done"),
    *jump_or_air_normal("scan_ground", "scan_done"),
    Label("scan_ground"),
    Ins("4eb90001ccda", "jsr $1ccda.l"),
    Branch("beq", "scan_done"),
    Ins("1d6e021303ab", "move.b $213(a6), $3ab(a6)"),
    Ins("1d7c000603ac", "move.b #$6, $3ac(a6)"),
    Label("scan_done"),
    Ins("422e03ae", "clr.b $3ae(a6)"),
    Ins("4a2e03ac", "tst.b $3ac(a6)"),
    Branch("bne", "active"),
    LeaPc("done", 0),
    Ins("4ed0", "jmp (a0)"),
    Label("active"),
    Ins("532e03ac", "subq.b #$1, $3ac(a6)"),
    Ins("4a6e006c", "tst.w $6c(a6)"),
    Branch("bgt", "alive"),
    LeaPc("clear", 0),
    Ins("4ed0", "jmp (a0)"),
    Label("alive"),
    # Visualmente a altura inteira zero já encosta no chão. Não espere
    # a física cruzar para negativo; só antecipa durante a descida.
    Ins("082e00040060", "btst.b #$4, $60(a6)"),
    Branch("bne", "check_air_landing"),
    LeaPc("ground", 0),
    Ins("4ed0", "jmp (a0)"),
    Label("check_air_landing"),
    *jump_or_air_normal("near_ground", "airborne"),
    Label("near_ground"),
    Ins("4a6e0018", "tst.w $18(a6)"),
    Branch("bgt", "airborne"),
    Ins("4aae0028", "tst.l $28(a6)"),
    Branch("bgt", "airborne"),
    Ins("42ae0018", "clr.l $18(a6)"),
    Ins("42ae0028", "clr.l $28(a6)"),
    Ins("42ac0028", "clr.l $28(a4)"),
    Ins("426e0030", "clr.w $30(a6)"),
    Ins("426e0034", "clr.w $34(a6)"),
    Ins("08ae00040060", "bclr.b #$4, $60(a6)"),
    Ins("08ee00020a68", "bset.b #$2, $a68(a6)"),
    Branch("bra", "ground"),
    Label("airborne"),
    LeaPc("done", 0),
    Ins("4ed0", "jmp (a0)"),
    Label("ground"),
    Ins("082e00020a68", "btst.b #$2, $a68(a6)"),
    Branch("bne", "landed"),
    LeaPc("done", 0),
    Ins("4ed0", "jmp (a0)"),
    Label("landed"),
    # Novos golpes, defesa, reação e especiais têm prioridade.
    Ins("0c2e00030040", "cmpi.b #$3, $40(a6)"),
    Branch("bne", "free_state"),
    Ins("0c6e002a0230", "cmpi.w #$2a, $230(a6)"),
    Branch("beq", "dash"),
    Ins("0c6e002b0230", "cmpi.w #$2b, $230(a6)"),
    Branch("beq", "dash"),
    Ins("0c6e003a0230", "cmpi.w #$3a, $230(a6)"),
    Branch("beq", "dash"),
    Ins("0c6e003b0230", "cmpi.w #$3b, $230(a6)"),
    Branch("beq", "dash"),
    Branch("bra", "clear"),
    Label("free_state"),
    Ins("0c2e00040040", "cmpi.b #$4, $40(a6)"),
    Branch("beq", "dash"),
    Ins("0c2e00080040", "cmpi.b #$8, $40(a6)"),
    Branch("beq", "dash"),
    Ins("0c2e00020040", "cmpi.b #$2, $40(a6)"),
    Branch("bhi", "clear"),
    Label("dash"),
    Ins("122e0068", "move.b $68(a6), d1"),
    Ins("02010003", "andi.b #$3, d1"),
    Branch("bne", "clear"),
    Ins("102e03ab", "move.b $3ab(a6), d0"),
    Ins("0c000004", "cmpi.b #$4, d0"),
    Branch("beq", "valid"),
    Ins("0c000008", "cmpi.b #$8, d0"),
    Branch("bne", "clear"),
    Label("valid"),
    Ins("422e0240", "clr.b $240(a6)"),
    Ins("08ae00070060", "bclr.b #$7, $60(a6)"),
    Ins("022e00f30270", "andi.b #$f3, $270(a6)"),
    Ins("812e0270", "or.b d0, $270(a6)"),
    Ins("4eb90001bc84", "jsr $1bc84.l"),
    # Aplica velocidade já nesta atualização, antes de copiar para o sprite.
    Ins("1d7c000103ad", "move.b #$1, $3ad(a6)"),
    Ins("4eb90001bd34", "jsr $1bd34.l"),
    Label("clear"),
    Ins("422e03ac", "clr.b $3ac(a6)"),
    Ins("422e03ab", "clr.b $3ab(a6)"),
    Label("done"),
    Ins("0c2e00100040", "cmpi.b #$10, $40(a6)"),
    Branch("beq", "restore"),
    Ins("0c2e00110040", "cmpi.b #$11, $40(a6)"),
    Branch("beq", "restore"),
    Ins("422e03ad", "clr.b $3ad(a6)"),
    Label("restore"),
    Ins("4cdf031f", "movem.l (a7)+, d0-d4/a0-a1"),
    Ins("4a2d0715", "tst.b $715(a5)"),
    Branch("beq", "normal"),
    JmpAbs(0x1B6E8),
    Label("normal"),
    JmpAbs(0x1B6F0),
]

# O dash da aterrissagem anda também nos seus quadros iniciais $40.
# A marca acaba na primeira fase em movimento; a pausa final fica original.
instant_start = [
    Ins("4a2e03ad", "tst.b $3ad(a6)"),
    Branch("beq", "original"),
    Ins("0c2e00100040", "cmpi.b #$10, $40(a6)"),
    Branch("beq", "dash"),
    Ins("0c2e00110040", "cmpi.b #$11, $40(a6)"),
    Branch("bne", "clear"),
    Label("dash"),
    Ins("4a2c0042", "tst.b $42(a4)"),
    Branch("bne", "start_move"),
    Ins("082e00060a69", "btst.b #$6, $a69(a6)"),
    Branch("beq", "clear"),
    Label("start_move"),
    JmpAbs(0x1BD34),
    Label("clear"),
    Ins("422e03ad", "clr.b $3ad(a6)"),
    Label("original"),
    Ins("082e00060a69", "btst.b #$6, $a69(a6)"),
    Branch("beq", "move"),
    JmpAbs(0x1BD26),
    Label("move"),
    JmpAbs(0x1BD34),
]

PATCH = Patch(
    id="landing-dash",
    title="Dash imediato ao aterrissar (buffer apenas de direcionais)",
    spec="src/backend/specs/SPEC-056-landing-dash.md",
    blocks=[Block("landing_air_taps", air_taps), Block("landing_dash", land),
            Block("landing_dash_start", instant_start)],
    hooks=[
        Hook(0x1C6CA, "08ae00020a6842ae0020", to_block="landing_air_taps"),
        Hook(0x1B6E2, "4a2d07156708", to_block="landing_dash"),
        Hook(0x1BD2C, "082e00060a6966f2", to_block="landing_dash_start"),
    ],
)
